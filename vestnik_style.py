# Words are style cues, not insert-on-every-story templates.
WORD_BANK={
 'обсуждение': ['срач','разбор полётов','словесная дуэль','показательный разнос'],
 'ошибка': ['проёб','обосраться','облажаться'],
 'фантазия': ['пиздёж','небылица','загнул'],
 'спор': ['сцепились','закусились','доебались до мелочи'],
 'смех': ['угар','ржач','добили шуткой'],
}

def relevant_words(evidence):
    text=' '.join(str(e.get('body','')) for e in evidence).lower()
    pool=[]
    if any(x in text for x in ['спор','доказ','нет,','неправ']):pool+=WORD_BANK['спор']
    if any(x in text for x in ['ошиб','случайн','забыл']):pool+=WORD_BANK['ошибка']
    if any(x in text for x in ['рж','хах','ахах']):pool+=WORD_BANK['смех']
    return pool[:8] # never force inclusion

def style_examples():
    return STYLES

def bad_cliche(text):
    return any(re.search(pattern,text,re.I) for pattern in BAD)

def too_long(text):
    return len(re.findall(r'\S+',text))>105

